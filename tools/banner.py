"""Draws the README banner's lettering as pixel blocks, so it needs no font.

GitHub shows the banner as an image, which cannot load web fonts, and system fonts
look generic. The letters are drawn on a 5x7 grid instead, in the same blocky spirit as
the floating block. Run `python tools/banner.py` after changing the text; it rewrites
the lettering between the markers in docs/assets/banner.svg.
"""

from pathlib import Path

GLYPHS = {
    "A": [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "B": ["####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."],
    "C": [".###.", "#...#", "#....", "#....", "#....", "#...#", ".###."],
    "E": ["#####", "#....", "#....", "####.", "#....", "#....", "#####"],
    "F": ["#####", "#....", "#....", "####.", "#....", "#....", "#...."],
    "G": [".###.", "#...#", "#....", "#.###", "#...#", "#...#", ".###."],
    "H": ["#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "I": [".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###."],
    "L": ["#....", "#....", "#....", "#....", "#....", "#....", "#####"],
    "M": ["#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"],
    "N": ["#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#", "#...#"],
    "O": [".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
    "P": ["####.", "#...#", "#...#", "####.", "#....", "#....", "#...."],
    "R": ["####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"],
    "S": [".####", "#....", "#....", ".###.", "....#", "....#", "####."],
    "T": ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."],
    "U": ["#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
    "V": ["#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#.."],
    "W": ["#...#", "#...#", "#...#", "#.#.#", "#.#.#", "##.##", "#...#"],
    "X": ["#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#"],
    ",": [".....", ".....", ".....", ".....", "..#..", "..#..", ".#..."],
    "·": [".....", ".....", ".....", "..#..", ".....", ".....", "....."],
}
SPACE = 3  # width of a space, in pixels of the grid


def text_width(text, px, gap):
    width = 0
    for ch in text:
        width += (SPACE if ch == " " else 5) * px + gap
    return width - gap


def runs(text, x, y, px, gap):
    """Rectangles (x, y, w, h) covering the lit pixels, merged along each row."""
    rects = []
    for ch in text:
        if ch == " ":
            x += SPACE * px + gap
            continue
        for row, line in enumerate(GLYPHS[ch]):
            col = 0
            while col < 5:
                if line[col] == "#":
                    start = col
                    while col < 5 and line[col] == "#":
                        col += 1
                    rects.append((x + start * px, y + row * px, (col - start) * px, px))
                else:
                    col += 1
        x += 5 * px + gap
    return rects


def top_edges(text, x, y, px, gap, height):
    """Thin strips along the top of each lit pixel with no lit pixel above it."""
    strips = []
    for ch in text:
        if ch == " ":
            x += SPACE * px + gap
            continue
        rows = GLYPHS[ch]
        for row, line in enumerate(rows):
            for col, cell in enumerate(line):
                above = rows[row - 1][col] if row > 0 else "."
                if cell == "#" and above != "#":
                    strips.append((x + col * px, y + row * px, px, height))
        x += 5 * px + gap
    return strips


def rect_svg(rects, fill, dx=0, dy=0, extra=""):
    return "\n".join(
        f'    <rect x="{x + dx:g}" y="{y + dy:g}" width="{w:g}" height="{h:g}" fill="{fill}"{extra}/>'
        for x, y, w, h in rects
    )


def lettering():
    left = 486
    # The wordmark: big blocks with a darker, deeper copy behind them.
    word_px, word_gap = 16, 18
    word = runs("LEVITAS", left, 84, word_px, word_gap)
    depth = rect_svg(word, "#7d2a05", dx=6, dy=6)
    side = rect_svg(word, "#c94a0c", dx=3, dy=3)
    face = rect_svg(word, "url(#word)")
    shine = rect_svg(
        top_edges("LEVITAS", left, 84, word_px, word_gap, 4),
        "#ffffff",
        extra=' opacity="0.5"',
    )
    width = text_width("LEVITAS", word_px, word_gap)
    accent = f'  <rect x="{left}" y="218" width="{width}" height="4" fill="#f74c00" opacity="0.85"/>'
    tagline = rect_svg(runs("SURVIVAL SERVER, WRITTEN IN RUST", left, 248, 4, 4), "#e6edf3")
    motto = rect_svg(runs("FAST · EXTENSIBLE · OPEN SOURCE", left, 304, 3, 3), "#8b949e")
    return "\n".join(
        [
            "  <!-- lettering: generated by tools/banner.py -->",
            '  <g shape-rendering="crispEdges">',
            depth,
            side,
            face,
            shine,
            "  </g>",
            accent,
            '  <g shape-rendering="crispEdges">',
            tagline,
            motto,
            "  </g>",
            "  <!-- end of lettering -->",
        ]
    )


def main():
    path = Path(__file__).resolve().parent.parent / "docs" / "assets" / "banner.svg"
    svg = path.read_text(encoding="utf-8")
    start = svg.index("  <!-- lettering: generated by tools/banner.py -->")
    end = svg.index("  <!-- end of lettering -->") + len("  <!-- end of lettering -->")
    path.write_text(svg[:start] + lettering() + svg[end:], encoding="utf-8", newline="\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
